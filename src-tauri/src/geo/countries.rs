/// 按国家码取中英文名；未知码回落到码本身，界面不会出现空白国家。
pub fn country_name(code: &str) -> (String, String) {
    let code = code.trim().to_uppercase();
    if code.is_empty() {
        return (String::new(), String::new());
    }
    COUNTRIES
        .iter()
        .find(|(iso, _, _)| *iso == code)
        .map(|(_, zh, en)| ((*zh).to_string(), (*en).to_string()))
        .unwrap_or_else(|| (code.clone(), code))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 常见国家码给出简体中英名() {
        assert_eq!(country_name("US"), ("美国".into(), "United States".into()));
        assert_eq!(country_name("ca"), ("加拿大".into(), "Canada".into()));
        assert_eq!(country_name("jp"), ("日本".into(), "Japan".into()));
        assert_eq!(
            country_name("HK"),
            ("中国香港".into(), "Hong Kong".into())
        );
    }

    #[test]
    fn 未知码回落为码本身而不是空() {
        assert_eq!(country_name("ZZ"), ("ZZ".into(), "ZZ".into()));
        assert_eq!(country_name(""), (String::new(), String::new()));
    }

    #[test]
    fn 表里没有重复的国家码() {
        let mut codes: Vec<&str> = COUNTRIES.iter().map(|(code, _, _)| *code).collect();
        let total = codes.len();
        codes.sort_unstable();
        codes.dedup();
        assert_eq!(codes.len(), total);
        assert!(total > 200, "国家表条目过少：{total}");
    }
}
